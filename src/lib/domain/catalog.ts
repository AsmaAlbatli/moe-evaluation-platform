export interface IndicatorRef extends IndicatorDef {
  domainId: DomainId;
  domainName: string;
  criterionCode: string;
  criterionName: string;
}

export const ALL_INDICATORS: IndicatorRef[] = DOMAINS.flatMap((d) =>
  d.criteria.flatMap((c) =>
    c.indicators.map((i) => ({
      ...i,
      domainId: d.id,
      domainName: d.name,
      criterionCode: c.code,
      criterionName: c.name,
    })),
  ),
);

export const INDICATOR_BY_CODE: ReadonlyMap<string, IndicatorRef> = new Map(
  ALL_INDICATORS.map((i) => [i.code, i]),
);

export const CRITERION_BY_CODE: ReadonlyMap<string, { code: string; name: string; domainId: DomainId }> =
  new Map(
    DOMAINS.flatMap((d) => d.criteria.map((c) => [c.code, { code: c.code, name: c.name, domainId: d.id }] as const)),
  );

export const DOMAIN_BY_ID: ReadonlyMap<number, DomainDef> = new Map(DOMAINS.map((d) => [d.id, d]));

export const CRITERIA_OF_DOMAIN = (domainId: DomainId): CriterionDef[] =>
  DOMAIN_BY_ID.get(domainId)?.criteria ?? [];

export const TOTAL_INDICATORS = ALL_INDICATORS.length;